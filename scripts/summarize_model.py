#!/usr/bin/env python3
"""Write docs/MODEL_SUMMARY.md from the .tflite flatbuffer (deterministic)."""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import tflite_ir  # noqa: E402

MODEL = Path("models/deit_tiny_patch16_224/deit_tiny_w8a8_pilot.tflite")
OUT = Path("docs/MODEL_SUMMARY.md")


def q(t) -> str:
    if len(t.scales) == 0:
        return "-"
    if len(t.scales) == 1:
        return f"s={float(t.scales[0]):.3g} zp={int(t.zero_points[0])}"
    return f"per-ch x{len(t.scales)} (dim {t.qdim})"


def main() -> None:
    m = tflite_ir.load(MODEL)
    T = m.tensors
    L: list[str] = []
    add = L.append

    add("# DeiT-Tiny W8A8 Model Summary")
    add("")
    add("Generated by `scripts/summarize_model.py` from the flatbuffer (no TFLite runtime).")
    add("")
    add(f"- File: `{m.path}`")
    add(f"- SHA-256: `{m.sha256}`")
    add(f"- Tensors: {len(T)}, ops: {len(m.ops)}")
    add(f"- Graph inputs: {[(i, T[i].name, T[i].dtype, list(T[i].shape)) for i in m.inputs]}")
    add(f"- Graph outputs: {[(i, T[i].name, T[i].dtype, list(T[i].shape)) for i in m.outputs]}")
    add("- Note: pilot export calibrated on ONE image; accuracy not qualified.")
    add("")

    # Constants
    const = [t for t in T if t.is_const]
    by_dtype = Counter()
    for t in const:
        by_dtype[t.dtype] += t.nbytes
    add("## Constant data (goes into .rodata)")
    add("")
    add("| dtype | bytes |")
    add("|---|---|")
    for k, v in sorted(by_dtype.items()):
        add(f"| {k} | {v:,} |")
    add(f"| **total** | **{sum(by_dtype.values()):,}** |")
    add("")

    # Op histogram
    hist = Counter(o.kind for o in m.ops)
    add("## Op histogram (whole model)")
    add("")
    add("| op | count |")
    add("|---|---|")
    for k, v in hist.most_common():
        add(f"| {k} | {v} |")
    add("")

    # Op sequence grouped by scope (name prefix before the op leaf)
    import re
    cur = ["(stem)"]

    def scope(o) -> str:
        # Carry the last seen Block_N forward: many intermediate tensors have no scope in name.
        for i in list(o.inputs) + list(o.outputs):
            if i < 0:
                continue
            mt = re.search(r"Block_(\d+)", T[i].name)
            if mt:
                cur[0] = f"Block_{mt.group(1)}"
                return cur[0]
        return cur[0]

    groups: dict[str, list] = {}
    order: list[str] = []
    for o in m.ops:
        s = scope(o)
        if s not in groups:
            groups[s] = []
            order.append(s)
        groups[s].append(o)

    add("## Ops per scope")
    add("")
    add("| scope | ops | op mix |")
    add("|---|---|---|")
    for s in order:
        c = Counter(o.kind for o in groups[s])
        mix = ", ".join(f"{k}x{v}" for k, v in c.most_common())
        add(f"| {s} | {len(groups[s])} | {mix} |")
    add("")

    # Full op listing for Block_0 (all blocks are identical in structure)
    add("## Block_0 op sequence (all 12 blocks share this structure)")
    add("")
    add("| # | op | inputs (tensor:shape:quant) | outputs | options |")
    add("|---|---|---|---|---|")

    def d(i: int) -> str:
        if i < 0:
            return "-"
        t = T[i]
        tag = "const " if t.is_const else ""
        return f"{i}:{tag}{t.dtype.lower()}{list(t.shape)} {q(t)}"

    for o in groups.get("Block_0", []):
        ins = "<br>".join(d(i) for i in o.inputs)
        outs = "<br>".join(d(i) for i in o.outputs)
        opts = ", ".join(f"{k}={v}" for k, v in o.options.items())
        add(f"| {o.idx} | {o.kind} | {ins} | {outs} | {opts} |")
    add("")

    # Non-block scopes
    for s in order:
        if s.startswith("Block_"):
            continue
        add(f"## Scope `{s}`")
        add("")
        add("| # | op | inputs | outputs | options |")
        add("|---|---|---|---|---|")
        for o in groups[s]:
            ins = "<br>".join(d(i) for i in o.inputs)
            outs = "<br>".join(d(i) for i in o.outputs)
            opts = ", ".join(f"{k}={v}" for k, v in o.options.items())
            add(f"| {o.idx} | {o.kind} | {ins} | {outs} | {opts} |")
        add("")

    # Heavy ops (MAC count)
    add("## Compute (MACs) by op kind")
    add("")
    macs: Counter = Counter()
    for o in m.ops:
        if o.kind == "FULLY_CONNECTED":
            w = T[o.inputs[1]]
            x = T[o.inputs[0]]
            rows = int(x.data.size if x.is_const else (x.nbytes // x.shape[-1]))
            macs[o.kind] += rows * w.shape[0] * w.shape[1]
        elif o.kind == "BATCH_MATMUL":
            a, b = T[o.inputs[0]], T[o.inputs[1]]
            ka = a.shape[-2] if o.options.get("adj_x") else a.shape[-1]
            batch = int(a.nbytes // (a.shape[-1] * a.shape[-2]))
            mm = a.shape[-1] if o.options.get("adj_x") else a.shape[-2]
            nn = b.shape[-2] if o.options.get("adj_y") else b.shape[-1]
            macs[o.kind] += batch * mm * ka * nn
        elif o.kind == "CONV_2D":
            w = T[o.inputs[1]]
            out = T[o.outputs[0]]
            oc, kh, kw, ic = w.shape
            macs[o.kind] += int(np_prod(out.shape[:3])) * kh * kw * ic * oc
    add("| op | MACs |")
    add("|---|---|")
    for k, v in macs.most_common():
        add(f"| {k} | {v:,} |")
    add(f"| **total** | **{sum(macs.values()):,}** |")
    add("")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(L)} lines)")


def np_prod(shape) -> int:
    n = 1
    for s in shape:
        n *= int(s)
    return n


if __name__ == "__main__":
    main()
