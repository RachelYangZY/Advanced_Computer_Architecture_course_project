#!/usr/bin/env python3
"""Derive integer requant params for the DeiT fc1 tile and emit C + golden INT8."""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
from ai_edge_litert import interpreter as tfl


def float_to_multiplier_shift(scale: float) -> tuple[int, int]:
    """Map real scale to (multiplier, shift) with scale ~= multiplier / 2^shift."""
    if scale <= 0.0:
        return 0, 0
    shift = 0
    scaled = float(scale)
    while scaled < (1 << 30) and shift < 31:
        scaled *= 2.0
        shift += 1
    multiplier = int(round(scaled))
    while multiplier > 2147483647:
        multiplier //= 2
        shift -= 1
    while multiplier < -(1 << 31):
        multiplier = (multiplier + (1 if multiplier > 0 else -1)) // 2
        shift -= 1
    return int(multiplier), int(shift)


def align_shifts(
    pairs: list[tuple[int, int]],
) -> tuple[list[int], int]:
    """Rewrite multipliers to a shared right-shift."""
    target_shift = max(shift for _, shift in pairs)
    multipliers = []
    for multiplier, shift in pairs:
        delta = target_shift - shift
        if delta > 0:
            multiplier = multiplier << delta
        multipliers.append(int(multiplier))
    return multipliers, target_shift


def requant_ref(
    acc: np.ndarray, multipliers: list[int], shift: int, zero_point: int
) -> np.ndarray:
    out = np.empty(acc.shape, dtype=np.int8)
    for row in range(acc.shape[0]):
        for col in range(acc.shape[1]):
            product = int(acc[row, col]) * int(multipliers[col])
            if shift > 0:
                rounding = 1 << (shift - 1)
                product = (product + rounding) >> shift
            product += zero_point
            out[row, col] = np.int8(np.clip(product, -128, 127))
    return out


def main() -> None:
    model = Path("models/deit_tiny_patch16_224/deit_tiny_w8a8_pilot.tflite")
    data_header = Path("src/workloads/deit_fc1_tile_data.h")
    out_header = Path("src/workloads/deit_fc1_requant_data.h")
    meta_path = Path("models/deit_tiny_patch16_224/deit_fc1_requant_meta.json")

    interp = tfl.Interpreter(str(model))
    interp.allocate_tensors()
    details = {t["index"]: t for t in interp.get_tensor_details()}

    weight = details[69]
    weight_scales = [float(x) for x in weight["quantization_parameters"]["scales"][:8]]
    act_scale = float(details[184]["quantization_parameters"]["scales"][0])
    out_scale = float(details[185]["quantization_parameters"]["scales"][0])
    out_zp = int(details[185]["quantization_parameters"]["zero_points"][0])

    pairs = []
    real_scales = []
    for weight_scale in weight_scales:
        real = (act_scale * weight_scale) / out_scale
        real_scales.append(real)
        pairs.append(float_to_multiplier_shift(real))
    multipliers, shift = align_shifts(pairs)

    # Load golden INT32 from the generated tile header.
    text = data_header.read_text(encoding="utf-8")
    start = text.index("deit_fc1_golden[] = {")
    end = text.index("};", start)
    body = text[start:end]
    values = [
        int(tok.strip().rstrip(","))
        for tok in body.replace("deit_fc1_golden[] = {", "").split(",")
        if tok.strip().rstrip(",").lstrip("-").isdigit()
    ]
    golden_i32 = np.array(values, dtype=np.int32).reshape(8, 8)
    golden_i8 = requant_ref(golden_i32, multipliers, shift, out_zp)

    lines = [
        "/* Auto-generated by tools/extract/generate_fc1_requant_params.py. Do not edit. */",
        "#ifndef DEIT_FC1_REQUANT_DATA_H",
        "#define DEIT_FC1_REQUANT_DATA_H",
        "",
        "#include <stdint.h>",
        "#include \"deit_fc1_tile_data.h\"",
        "",
        f"#define DEIT_FC1_REQUANT_SHIFT {shift}",
        f"#define DEIT_FC1_REQUANT_ZERO_POINT {out_zp}",
        "",
        "static const int32_t deit_fc1_requant_multipliers[DEIT_FC1_TILE_COLUMNS] = {",
        "    " + ", ".join(str(m) for m in multipliers) + ",",
        "};",
        "",
        "static const int8_t deit_fc1_requant_golden[] = {",
    ]
    flat = golden_i8.reshape(-1)
    for i in range(0, flat.size, 16):
        chunk = ", ".join(str(int(v)) for v in flat[i : i + 16])
        lines.append(f"    {chunk},")
    lines += ["};", "", "#endif", ""]
    out_header.write_text("\n".join(lines), encoding="utf-8")

    meta = {
        "input_id": "deit-block0-mlp-fc1-tile-requant-v1",
        "act_tensor_index": 184,
        "act_scale": act_scale,
        "weight_tensor_index": 69,
        "weight_scales_tile": weight_scales,
        "out_tensor_index": 185,
        "out_scale": out_scale,
        "out_zero_point": out_zp,
        "real_scales": real_scales,
        "multipliers": multipliers,
        "shift": shift,
        "notes": (
            "Applies model-derived per-channel effective scales to the existing "
            "raw INT32 GEMM tile. Does not subtract activation zero-points or add "
            "bias; intended for scalar requant ISA comparison on this tile."
        ),
        "golden_i8_corners": {
            "output[0]": int(golden_i8[0, 0]),
            "output[1]": int(golden_i8[0, 1]),
            "output[last]": int(golden_i8[-1, -1]),
        },
    }
    meta_path.write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
